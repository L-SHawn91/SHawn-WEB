#!/usr/bin/env node
/**
 * Build a Vercel-safe SHawn-WEB search ontology from the local SHawn paper
 * corpus DB.  This script is intentionally local/offline: Vercel must consume
 * the generated JavaScript bundle, not the live SQLite DB.
 *
 * Default output is a candidate JSON under /tmp for curator review.  Use
 * `--write-js` only after reviewing that the generated vocabulary contains
 * public/generic venue/topic terms and no credentials, raw private data, or
 * licensed JCR metrics.
 */
import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { homedir } from 'node:os';

const args = new Set(process.argv.slice(2));
const defaultDbPath = resolve(homedir(), 'SHawn/Paper-mapping/_pmap_index/corpus.db');
const dbPath = process.env.SHAWN_WEB_PAPER_CORPUS_DB || defaultDbPath;
const outJson = process.env.SHAWN_WEB_SEARCH_ONTOLOGY_JSON || '/tmp/shawn_web_search_ontology_candidate.json';
const outJs = resolve('lib/search/searchOntologyData.js');

if (!existsSync(dbPath)) {
  console.error(`[search-ontology] corpus DB not found: ${dbPath}`);
  process.exit(2);
}

const py = String.raw`
import json, re, sqlite3, sys
from collections import Counter

DB=sys.argv[1]
conn=sqlite3.connect(f'file:{DB}?mode=ro', uri=True)
conn.row_factory=sqlite3.Row
cur=conn.cursor()

def norm(s):
    return re.sub(r'[^a-z0-9]+', ' ', (s or '').lower()).strip()

venues=[]
for row in cur.execute("select venue, count(*) n from paper where venue is not null and trim(venue)<>'' group by venue order by n desc, venue limit 2000"):
    v=norm(row['venue'])
    if len(v) >= 3:
        venues.append(v)

stop=set('a an and are as at based by for from in into is of on or the to using with without via within between after before during current role roles review reviews study studies analysis analyses'.split())
venue_words=set('journal journals reports reviews review frontiers proceedings letters communications transactions annals annual archives bulletin biology reproductive reproduction endocrinology oncology medicine sciences molecular surgical immunological scientific international clinical science world'.split())
base_bio=set('endometrium endometrial uterus uterine organoid organoids single cell cells scrna rnaseq rna sequencing elisa western blot immunohistochemistry pcr pathway expression gene genes protein kinase receptor placenta mouse human pig porcine swine disease syndrome cancer endometriosis progesterone estrogen trophoblast embryo implantation'.split())
counts=Counter()
for row in cur.execute("select title from paper where title is not null and trim(title)<>'' limit 10000"):
    words=norm(row['title']).split()
    for w in words:
        if len(w) < 4 or w in stop:
            continue
        if w in venue_words:
            continue
        if w in base_bio or re.search(r'(ase|kinase|receptor|globulin|omics|ation|itis|osis)$', w):
            counts[w]+=1
bio_terms=sorted(base_bio | {w for w,c in counts.items() if c >= 3})

payload={
  'version':'candidate-from-corpus-db',
  'source':'paper.venue plus frequent public title bio/method terms; no authors/JCR metrics',
  'venues':venues,
  'venueFragments':sorted(venue_words),
  'venueTerminals':sorted({'journal','journals','reports','reviews','letters','communications','proceedings','biology','reproduction','endocrinology','oncology','medicine','sciences','cell'}),
  'bioTerms':bio_terms,
  'counts': {'venues': len(venues), 'bioTerms': len(bio_terms)},
}
print(json.dumps(payload, ensure_ascii=False, indent=2))
`;

const res = spawnSync('python3', ['-c', py, dbPath], { encoding: 'utf8', maxBuffer: 20 * 1024 * 1024 });
if (res.status !== 0) {
  process.stderr.write(res.stderr || res.stdout);
  process.exit(res.status || 1);
}
const payload = JSON.parse(res.stdout);

// Stamp a dated version so curators can tell when the candidate was generated.
const datestamp = new Date().toISOString().slice(0, 10);
payload.version = `${datestamp}.candidate`;

mkdirSync(dirname(outJson), { recursive: true });
writeFileSync(outJson, JSON.stringify(payload, null, 2) + '\n');
console.log(`[search-ontology] wrote candidate JSON: ${outJson}`);
console.log(`[search-ontology] version: ${payload.version}  counts: ${JSON.stringify(payload.counts)}`);

if (args.has('--write-js')) {
  const q = (arr) => arr.map((v) => `  ${JSON.stringify(v)},`).join('\n');
  const js = `// Vercel-safe, bundled search ontology for paper-search query intent.\n// Generated by scripts/build-search-ontology.mjs after local curator review.\n// Contains public/generic vocabulary only; no credentials, raw DB rows, JCR metrics, or private caches.\n\nexport const SEARCH_ONTOLOGY_VERSION = ${JSON.stringify(payload.version)};\n\nexport const SEARCH_ONTOLOGY_VENUES = [\n${q(payload.venues)}\n];\n\nexport const SEARCH_ONTOLOGY_VENUE_FRAGMENTS = [\n${q(payload.venueFragments)}\n];\n\nexport const SEARCH_ONTOLOGY_VENUE_TERMINALS = [\n${q(payload.venueTerminals)}\n];\n\nexport const SEARCH_ONTOLOGY_BIO_TERMS = [\n${q(payload.bioTerms)}\n];\n`;
  mkdirSync(dirname(outJs), { recursive: true });
  writeFileSync(outJs, js);
  console.log(`[search-ontology] wrote JS bundle: ${outJs}`);
  console.log('[search-ontology] run `pnpm run check:search-ontology` to verify the bundle before committing.');
} else {
  console.log('[search-ontology] review JSON first; rerun with --write-js to update bundled Vercel ontology.');
}
